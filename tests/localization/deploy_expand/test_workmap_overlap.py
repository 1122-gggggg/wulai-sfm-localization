def _scene(*, count: int = 24, scale: float = 1.35, identity: bool = False):
    rng = np.random.default_rng(20260926)
    K = np.array(
        [[620.0, 0.0, 320.0], [0.0, 610.0, 240.0], [0.0, 0.0, 1.0]],
        dtype=np.float64,
    )
    old_xyz = np.column_stack(
        (
            rng.uniform(-1.2, 1.2, count),
            rng.uniform(-0.8, 0.8, count),
            rng.uniform(6.0, 9.0, count),
        )
    )
    angle = 0.17
    rotation = np.array(
        [
            [np.cos(angle), 0.0, np.sin(angle)],
            [0.0, 1.0, 0.0],
            [-np.sin(angle), 0.0, np.cos(angle)],
        ],
        dtype=np.float64,
    )
    translation = np.array([0.28, -0.19, 0.36], dtype=np.float64)
    if identity:
        scale = 1.0
        rotation = np.eye(3)
        translation = np.zeros(3)
    new_xyz = ((old_xyz - translation) @ rotation) / scale
    rows = []
    new_ids = -np.arange(1, count + 1, dtype=np.int64)
    landmark_revisions = {int(new_id): 4 for new_id in new_ids}
    old_projection = (K @ old_xyz.T).T
    old_xy = old_projection[:, :2] / old_projection[:, 2:3]

    # Three genuine camera views: every measured pixel is generated by the
    # source KF pose and the corresponding local 3D landmark.
    for index, center in enumerate(([0.0, 0.0, 0.0], [0.24, -0.04, 0.0], [-0.18, 0.07, 0.0])):
        pose = np.column_stack((np.eye(3), -np.asarray(center, dtype=np.float64)))
        camera_xyz = (pose[:, :3] @ new_xyz.T).T + pose[:, 3]
        projected = (K @ camera_xyz.T).T
        image_xy = projected[:, :2] / projected[:, 2:3]
        for row_index, new_id in enumerate(new_ids):
            rows.append(
                {
                    "new_id": int(new_id),
                    "old_id": int(row_index + 101),
                    "new_xyz": new_xyz[row_index].tolist(),
                    "old_xyz": old_xyz[row_index].tolist(),
                    "new_xy": image_xy[row_index].tolist(),
                    "old_xy": old_xy[row_index].tolist(),
                    "old_reference_name": "frozen-reference-kf-2",
                    "confidence": 0.95,
                    "keyframe_name": f"session-kf-{index}",
                    "keyframe_revision": 20 + index,
                    "pose_revision": 30 + index,
                    "landmark_revisions": landmark_revisions,
                    "keyframe_pose": pose.tolist(),
                    "keyframe_K": K.tolist(),
                    "image_size": [640, 480],
                    "session_id": "session-test",
                    "source_epoch": 3,
                }
            )
    expected = {"scale": scale, "rotation": rotation, "translation": translation}
    return rows, expected


def test_fit_overlap_recovers_injected_sim3_and_independent_multiview_holdout():
    evidence, expected = _scene()

    result = fit_overlap_sim3(evidence)
    repeated = fit_overlap_sim3(evidence)

    assert result["ok"] is True, result
    assert result == repeated
    assert result["scale"] == pytest.approx(expected["scale"], rel=1e-8)
    np.testing.assert_allclose(result["rotation"], expected["rotation"], atol=1e-8)
    np.testing.assert_allclose(result["translation"], expected["translation"], atol=1e-8)
    assert len(result["source_keyframes"]) == 3
    assert len(result["fit_new_ids"]) >= 6
    assert len(result["holdout_new_ids"]) >= 6
    assert set(result["fit_new_ids"]).isdisjoint(result["holdout_new_ids"])
    assert result["after_3d_p90"] < result["before_3d_p90"]
    assert result["after_2d_p90"] < result["before_2d_p90"]


def test_repeated_multiview_identity_is_never_leaked_between_fit_and_holdout():
    evidence, _ = _scene()
    result = fit_overlap_sim3(evidence)

    assert result["ok"] is True, result
    assert len(result["fit_new_ids"]) + len(result["holdout_new_ids"]) == 24
    assert set(result["fit_new_ids"]).isdisjoint(result["holdout_new_ids"])
    assert len(evidence) == 24 * 3

    # Each identity has three observed views, but changing only reserved
    # holdout XYZ must not change the fitted transform.
    holdout = set(result["holdout_new_ids"])
    for row in evidence:
        if row["new_id"] in holdout:
            row["old_xyz"] = (np.asarray(row["old_xyz"]) + [0.001, 0.0, 0.0]).tolist()
    perturbed = fit_overlap_sim3(evidence)
    assert perturbed["ok"] is True, perturbed
    assert perturbed["fit_new_ids"] == result["fit_new_ids"]
    assert perturbed["holdout_new_ids"] == result["holdout_new_ids"]
    assert perturbed["scale"] == pytest.approx(result["scale"], abs=1e-12)
    np.testing.assert_allclose(perturbed["rotation"], result["rotation"], atol=1e-12)
    np.testing.assert_allclose(perturbed["translation"], result["translation"], atol=1e-12)


def test_fit_rejects_collinear_identity_geometry():
    evidence, _ = _scene()
    for row in evidence:
        new_id = int(row["new_id"])
        coordinate = float(-new_id)
        row["new_xyz"] = [coordinate, 0.0, 4.0]
        row["old_xyz"] = [coordinate * 1.5 + 0.2, 0.0, 6.0]

    result = fit_overlap_sim3(evidence)

    assert result["ok"] is False
    assert "non-collinear" in result["reason"]


def test_ransac_rejects_a_fit_identity_outlier_without_using_holdout_ids():
    evidence, _ = _scene()
    baseline = fit_overlap_sim3(evidence)
    assert baseline["ok"] is True, baseline
    outlier_id = baseline["fit_new_ids"][0]
    for row in evidence:
        if row["new_id"] == outlier_id:
            row["old_xyz"] = (np.asarray(row["old_xyz"]) + [12.0, -8.0, 5.0]).tolist()

    result = fit_overlap_sim3(evidence)

    assert result["ok"] is True, result
    assert outlier_id not in result["fit_new_ids"]
    assert set(result["fit_new_ids"]).isdisjoint(result["holdout_new_ids"])


def test_corrupted_holdout_identity_is_not_dropped_to_make_fit_look_better():
    evidence, _ = _scene()
    baseline = fit_overlap_sim3(evidence)
    assert baseline["ok"] is True, baseline
    outlier_id = baseline["holdout_new_ids"][0]
    for row in evidence:
        if row["new_id"] == outlier_id:
            row["old_xyz"] = (np.asarray(row["old_xyz"]) + [10.0, 3.0, -4.0]).tolist()

    result = fit_overlap_sim3(evidence)

    assert result["ok"] is False
    assert "holdout" in result["reason"]


def test_duplicate_and_conflicting_identity_evidence_is_rejected():
    evidence, _ = _scene()
    conflicting_new = dict(evidence[0])
    conflicting_new["old_id"] = 9999
    conflicting_new["old_xyz"] = [1.0, 2.0, 8.0]
    assert "conflicting old identities" in fit_overlap_sim3(evidence + [conflicting_new])["reason"]

    evidence, _ = _scene()
    conflicting_old = dict(evidence[0])
    conflicting_old["new_id"] = -9999
    conflicting_old["landmark_revisions"] = {-9999: 4}
    conflicting_old["new_xyz"] = [0.2, 0.1, 4.0]
    assert "conflicting new identities" in fit_overlap_sim3(evidence + [conflicting_old])["reason"]

    evidence, _ = _scene()
    assert (
        "duplicate identity observation"
        in fit_overlap_sim3(evidence + [dict(evidence[0])])["reason"]
    )


def test_missing_or_inconsistent_landmark_revision_is_rejected():
    evidence, _ = _scene()
    evidence[0]["landmark_revisions"] = {}
    result = fit_overlap_sim3(evidence)
    assert result["ok"] is False
    assert "missing landmark revision" in result["reason"]

    evidence, _ = _scene()
    evidence[0]["landmark_revisions"] = {evidence[0]["new_id"]: 5}
    result = fit_overlap_sim3(evidence)
    assert result["ok"] is False
    assert "conflicting landmark revisions" in result["reason"]


def test_no_error_does_not_trigger_an_unconditional_correction():
    evidence, _ = _scene(identity=True)

    result = fit_overlap_sim3(evidence)

    assert result["ok"] is False
    assert "does not genuinely improve" in result["reason"]


def test_insufficient_unique_pairs_and_invalid_id_signs_are_rejected():
    evidence, _ = _scene(count=11)
    result = fit_overlap_sim3(evidence)
    assert result["ok"] is False
    assert "twelve unique overlap identities" in result["reason"]

    evidence, _ = _scene()
    evidence[0]["new_id"] = abs(evidence[0]["new_id"])
    result = fit_overlap_sim3(evidence)
    assert result["ok"] is False
    assert "new_id < 0" in result["reason"]


def test_source_keyframe_pose_and_image_bounds_are_required():
    evidence, _ = _scene()
    del evidence[0]["keyframe_pose"]
    assert fit_overlap_sim3(evidence)["ok"] is False

    evidence, _ = _scene()
    evidence[0]["new_xy"] = [640.0, 200.0]
    result = fit_overlap_sim3(evidence)
    assert result["ok"] is False
    assert "outside source image" in result["reason"]
